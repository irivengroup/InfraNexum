const CONTINENT_KEYS = Object.freeze({
  'Africa': 'country.continent.africa',
  'North America': 'country.continent.northAmerica',
  'South America': 'country.continent.southAmerica',
  'Asia': 'country.continent.asia',
  'Europe': 'country.continent.europe',
  'Oceania': 'country.continent.oceania',
  'Antarctica': 'country.continent.antarctica',
  'Other': 'country.continent.other',
});

export function groupedCountries(locale = 'en') {
  const displayNames = countryDisplayNames(locale);
  const groups = new Map();
  for (const country of COUNTRY_CATALOG) {
    if (!groups.has(country.continent)) groups.set(country.continent, []);
    groups.get(country.continent).push(Object.freeze({
      code: country.code,
      name: displayNames?.of(country.code) || country.name,
    }));
  }
  return Object.freeze([...groups.entries()].map(([continent, countries]) => Object.freeze({
    continent,
    labelKey: CONTINENT_KEYS[continent],
    countries: Object.freeze(countries.sort((a, b) => a.name.localeCompare(b.name, locale))),
  })));
}

export function initializeCountrySelects(documentObject = document, locale = documentObject?.documentElement?.lang || 'en') {
  let count = 0;
  for (const select of documentObject?.querySelectorAll?.('select[data-inx-country-select]') ?? []) {
    populateCountrySelect(documentObject, select, locale);
    count += 1;
  }
  return count;
}

export function populateCountrySelect(documentObject, select, locale = 'en') {
  const previous = String(select.value ?? '').toUpperCase();
  const placeholder = documentObject.createElement('option');
  placeholder.value = '';
  placeholder.textContent = '—';
  placeholder.disabled = select.required === true;
  const nodes = [placeholder];
  for (const group of groupedCountries(locale)) {
    const optgroup = documentObject.createElement('optgroup');
    optgroup.label = localizedContinent(group.continent, locale);
    for (const country of group.countries) {
      const option = documentObject.createElement('option');
      option.value = country.code;
      option.textContent = country.name;
      optgroup.appendChild(option);
    }
    nodes.push(optgroup);
  }
  select.replaceChildren(...nodes);
  if (previous && COUNTRY_CATALOG.some((country) => country.code === previous)) select.value = previous;
  else select.value = '';
  select.setAttribute?.('data-inx-country-ready', 'true');
  const EventConstructor = documentObject?.defaultView?.Event ?? globalThis.Event;
  if (typeof EventConstructor === 'function') select.dispatchEvent?.(new EventConstructor('infranexum:entity-sync', { bubbles: false }));
}

function countryDisplayNames(locale) {
  try { return new Intl.DisplayNames([locale || 'en'], { type: 'region' }); } catch { return null; }
}
function localizedContinent(continent, locale) {
  const labels = {
    en: { Africa:'Africa','North America':'North America','South America':'South America',Asia:'Asia',Europe:'Europe',Oceania:'Oceania',Antarctica:'Antarctica',Other:'Other' },
    fr: { Africa:'Afrique','North America':'Amérique du Nord','South America':'Amérique du Sud',Asia:'Asie',Europe:'Europe',Oceania:'Océanie',Antarctica:'Antarctique',Other:'Autres' },
    de: { Africa:'Afrika','North America':'Nordamerika','South America':'Südamerika',Asia:'Asien',Europe:'Europa',Oceania:'Ozeanien',Antarctica:'Antarktika',Other:'Andere' },
    es: { Africa:'África','North America':'América del Norte','South America':'América del Sur',Asia:'Asia',Europe:'Europa',Oceania:'Oceanía',Antarctica:'Antártida',Other:'Otros' },
    it: { Africa:'Africa','North America':'America del Nord','South America':'America del Sud',Asia:'Asia',Europe:'Europa',Oceania:'Oceania',Antarctica:'Antartide',Other:'Altro' },
  };
  const language = String(locale || 'en').toLowerCase().split('-')[0];
  return labels[language]?.[continent] || labels.en[continent] || continent;
}
